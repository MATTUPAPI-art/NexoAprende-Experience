import {
  closeSync,
  existsSync,
  openSync,
  readFileSync,
  readSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { format } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requested = {
  cover: ['videos/optimized/portada-educativa.webm', 'videos/portada-educativa.mp4'],
  activities: ['videos/optimized/actividades-ninos.webm', 'videos/actividades-ninos.mp4'],
  child: ['images/optimized/etapa-infantil.webp', 'images/etapas/etapa-infantil.jpg'],
  junior: ['images/optimized/etapa-juvenil.webp', 'images/etapas/etapa-juvenil.jpg'],
  teen: ['images/optimized/etapa-adolescente.webp', 'images/etapas/etapa-adolescente.jpg'],
};
const art = {
  logo: ['logo', 'logo-nexoaprende'],
  favicon: ['logo', 'favicon-nexoaprende'],
  nexito: ['mascota', 'nexito'],
  victory: ['mascota', 'nexito-victoria'],
  welcome: ['mascota', 'nexito-bienvenida'],
  childWorld: ['fondos', 'fondo-infantil'],
  juniorWorld: ['fondos', 'fondo-juvenil'],
  teenWorld: ['fondos', 'fondo-adolescente'],
  coverArt: ['fondos', 'portada-principal'],
  catalog: ['fondos', 'fondo-actividades'],
  tutor: ['fondos', 'fondo-tutores'],
  professional: ['fondos', 'fondo-profesionales'],
  dashboard: ['fondos', 'fondo-mi-espacio'],
  progress: ['fondos', 'fondo-progreso'],
  memory: ['fondos', 'fondo-memoria'],
  attention: ['fondos', 'fondo-atencion'],
  reading: ['fondos', 'fondo-lectura'],
};
for (const [key, [folder, name]] of Object.entries(art))
  requested[key] = [`images/optimized/${name}.webp`, `images/${folder}/${name}.png`];
const assets = {};
const missing = [];
for (const [key, candidates] of Object.entries(requested)) {
  for (const relative of candidates) {
    const path = resolve(root, 'public', relative);
    let valid = existsSync(path) && statSync(path).isFile();
    if (valid) {
      const descriptor = openSync(path, 'r');
      const header = Buffer.alloc(64);
      try {
        readSync(descriptor, header, 0, 64, 0);
      } finally {
        closeSync(descriptor);
      }
      valid = relative.endsWith('.png')
        ? header.subarray(0, 8).toString('hex') === '89504e470d0a1a0a'
        : relative.endsWith('.jpg')
          ? header[0] === 0xff && header[1] === 0xd8 && header[2] === 0xff
          : relative.endsWith('.webp')
            ? header.toString('ascii', 0, 4) === 'RIFF' &&
              header.toString('ascii', 8, 12) === 'WEBP'
            : relative.endsWith('.webm')
              ? header[0] === 0x1a && header[1] === 0x45 && header[2] === 0xdf && header[3] === 0xa3
              : header.toString('ascii', 4, 8) === 'ftyp';
    }
    if (valid) {
      assets[key] = relative;
      break;
    }
  }
  if (!assets[key]) missing.push(candidates[candidates.length - 1]);
}
const output = resolve(root, 'src/app/core/constants/media-manifest.ts');
const enabled =
  JSON.parse(readFileSync(resolve(root, 'media.config.json'), 'utf8')).enabled === true;
const activeAssets = enabled ? assets : {};
const indexPath = resolve(root, 'src/index.html');
const indexSource = readFileSync(indexPath, 'utf8');
const favicon = activeAssets.favicon ?? 'favicon.svg';
const updatedIndex = indexSource.replace(
  /<link rel="icon"[^>]*\/>/,
  `<link rel="icon" type="${favicon.endsWith('.svg') ? 'image/svg+xml' : favicon.endsWith('.png') ? 'image/png' : 'image/webp'}" href="${favicon}" />`,
);
if (updatedIndex !== indexSource) writeFileSync(indexPath, updatedIndex);
const rawSource =
  '// Generated by scripts/prepare-media.mjs. Only existing, valid local files are exposed.\n' +
  "import { Stage } from '../models/models';\n" +
  'export const MEDIA: { cover?: string; activities?: string; stages: Partial<Record<Stage, string>>; worlds: Partial<Record<Stage, string>>; art: Partial<Record<' +
  Object.keys(art)
    .map((key) => JSON.stringify(key))
    .join(' | ') +
  ', string>> } = ' +
  JSON.stringify(
    {
      cover: activeAssets.cover,
      activities: activeAssets.activities,
      stages: { child: activeAssets.child, junior: activeAssets.junior, teen: activeAssets.teen },
      worlds: {
        child: activeAssets.childWorld,
        junior: activeAssets.juniorWorld,
        teen: activeAssets.teenWorld,
      },
      art: Object.fromEntries(
        Object.keys(art)
          .filter((key) => activeAssets[key])
          .map((key) => [key, activeAssets[key]]),
      ),
    },
    null,
    2,
  ) +
  ';\n';
const source = await format(rawSource, {
  parser: 'typescript',
  singleQuote: true,
  printWidth: 100,
});
if (!existsSync(output) || readFileSync(output, 'utf8') !== source) writeFileSync(output, source);
console.log(
  `[multimedia] ${Object.keys(assets).length}/${Object.keys(requested).length} recursos locales disponibles.`,
);
if (!enabled)
  console.log('[multimedia] Integración desactivada: versión CSS/SVG para revisión visual.');
if (missing.length) console.log('[multimedia] Alternativa gráfica para: ' + missing.join(', '));
